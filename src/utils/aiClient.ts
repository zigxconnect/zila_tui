import { loadAgentConfig, type AIProviderConfig } from "./aiConfig.js";

export interface ChatMessage {
  role: "system" | "user" | "assistant";
  content: string;
}

export interface ChatCompletionOptions {
  temperature?: number;
  maxTokens?: number;
}

/**
 * Universal Unified AI Client.
 * Connects directly to Google Gemini, Groq, Anthropic Claude, OpenAI, or OpenRouter
 * based on student's configured provider.
 */
export async function generateChatResponse(
  messages: ChatMessage[],
  options: ChatCompletionOptions = {},
): Promise<string> {
  const config = loadAgentConfig();
  if (!config) {
    throw new Error(
      "No AI provider configured. Please run 'agent --setup' or set your API key environment variables.",
    );
  }

  switch (config.provider) {
    case "gemini":
      return await callGemini(config, messages, options);
    case "groq":
      return await callOpenAICompatible(config, "https://api.groq.com/openai/v1/chat/completions", messages, options);
    case "openai":
      return await callOpenAICompatible(config, "https://api.openai.com/v1/chat/completions", messages, options);
    case "openrouter":
      return await callOpenAICompatible(config, "https://openrouter.ai/api/v1/chat/completions", messages, options);
    case "claude":
      return await callClaude(config, messages, options);
    default:
      throw new Error(`Unsupported AI provider: ${config.provider}`);
  }
}

/**
 * Streaming version that yields chunks for terminal interfaces.
 */
export async function* streamChatResponse(
  messages: ChatMessage[],
  options: ChatCompletionOptions = {},
): AsyncGenerator<string, void, unknown> {
  // Simple buffer or full stream fallback:
  const fullText = await generateChatResponse(messages, options);
  // Yield in natural chunks for smooth rendering:
  const words = fullText.split(/(\s+)/);
  for (const word of words) {
    yield word;
    await new Promise((r) => setTimeout(r, 15));
  }
}

async function callGemini(
  config: AIProviderConfig,
  messages: ChatMessage[],
  options: ChatCompletionOptions,
): Promise<string> {
  const model = config.model || "gemini-2.5-flash";
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${config.apiKey}`;

  // Map messages to Gemini format
  const contents = messages
    .filter((m) => m.role !== "system")
    .map((m) => ({
      role: m.role === "assistant" ? "model" : "user",
      parts: [{ text: m.content }],
    }));

  const systemMessage = messages.find((m) => m.role === "system");
  const systemInstruction = systemMessage ? { parts: [{ text: systemMessage.content }] } : undefined;

  const payload: any = {
    contents,
    generationConfig: {
      temperature: options.temperature ?? 0.7,
      maxOutputTokens: options.maxTokens ?? 2048,
    },
  };
  if (systemInstruction) {
    payload.systemInstruction = systemInstruction;
  }

  const res = await fetch(url, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(payload),
  });

  if (!res.ok) {
    const errorBody = await res.json().catch(() => ({}));
    throw new Error(`Gemini API Error: ${(errorBody as any)?.error?.message || res.statusText}`);
  }

  const data: any = await res.json();
  const candidate = data.candidates?.[0];
  const text = candidate?.content?.parts?.[0]?.text;
  if (!text) {
    throw new Error("No response generated by Gemini model");
  }
  return text;
}

async function callOpenAICompatible(
  config: AIProviderConfig,
  endpoint: string,
  messages: ChatMessage[],
  options: ChatCompletionOptions,
): Promise<string> {
  const model = config.model || (config.provider === "groq" ? "llama-3.3-70b-versatile" : "gpt-4o");

  const res = await fetch(endpoint, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${config.apiKey}`,
    },
    body: JSON.stringify({
      model,
      messages,
      temperature: options.temperature ?? 0.7,
      max_tokens: options.maxTokens ?? 2048,
    }),
  });

  if (!res.ok) {
    const errorBody = await res.json().catch(() => ({}));
    throw new Error(`${config.provider} API Error: ${(errorBody as any)?.error?.message || res.statusText}`);
  }

  const data: any = await res.json();
  const choice = data.choices?.[0];
  const text = choice?.message?.content;
  if (!text) {
    throw new Error(`No response generated by ${config.provider}`);
  }
  return text;
}

async function callClaude(
  config: AIProviderConfig,
  messages: ChatMessage[],
  options: ChatCompletionOptions,
): Promise<string> {
  const model = config.model || "claude-3-5-sonnet-latest";
  const systemMessage = messages.find((m) => m.role === "system");
  const nonSystemMessages = messages
    .filter((m) => m.role !== "system")
    .map((m) => ({ role: m.role, content: m.content }));

  const res = await fetch("https://api.anthropic.com/v1/messages", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "x-api-key": config.apiKey,
      "anthropic-version": "2023-06-01",
    },
    body: JSON.stringify({
      model,
      system: systemMessage?.content,
      messages: nonSystemMessages,
      max_tokens: options.maxTokens ?? 2048,
      temperature: options.temperature ?? 0.7,
    }),
  });

  if (!res.ok) {
    const errorBody = await res.json().catch(() => ({}));
    throw new Error(`Anthropic Claude Error: ${(errorBody as any)?.error?.message || res.statusText}`);
  }

  const data: any = await res.json();
  const text = data.content?.[0]?.text;
  if (!text) {
    throw new Error("No response generated by Claude");
  }
  return text;
}
