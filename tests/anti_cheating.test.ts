test("Anti-Cheating - scanFilesForAiWatermarks detects AI boilerplate and comments", () => {
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), "zila-ai-watermark-test-"));
  try {
    const aiFile = path.join(tmpDir, "solution.ts");
    fs.writeFileSync(
      aiFile,
      `// Here is the complete code implementation as requested:\n// Generated by ChatGPT\nexport function solve() { return 42; }\n// Certainly! Here is the code`,
      "utf-8"
    );

    const findings = scanFilesForAiWatermarks(tmpDir);
    assert.equal(findings.found, true);
    assert.ok(findings.matches.length >= 2);
    assert.ok(findings.matches.some(f => f.includes("ChatGPT")));
    assert.ok(findings.matches.some(f => f.includes("Certainly! Here")));
  } finally {
    fs.rmSync(tmpDir, { recursive: true, force: true });
  }
});

test("Supervisor Instructions - findSupervisorInstructionsInFolder reads dedicated instruction files", () => {
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), "zila-supervisor-folder-test-"));
  try {
    // Hidden supervisor file not visible in exercise.md
    const hiddenFile = path.join(tmpDir, ".supervisor_instructions");
    fs.writeFileSync(
      hiddenFile,
      JSON.stringify({
        task: "Build concurrent worker queue",
        requirements: ["Thread pool of 4 workers", "Graceful shutdown signal handling"],
        gradingWeight: 1.5,
        criteriaNotes: "Ensure zero race conditions on queue buffer",
      }),
      "utf-8"
    );

    const extracted = findSupervisorInstructionsInFolder(tmpDir);
    assert.equal(extracted.hasInstructions, true);
    assert.equal(extracted.taskDescription, "Build concurrent worker queue");
    assert.equal(extracted.requirements.length, 2);
    assert.equal(extracted.requirements[0], "Thread pool of 4 workers");
    assert.equal(extracted.weight, 1.5);
  } finally {
    fs.rmSync(tmpDir, { recursive: true, force: true });
  }
});

test("Honest Evaluator - factor cheating analysis into proposed mark (0.0 to 1.0)", async () => {
  const instructions = {
    hasInstructions: true,
    rawHeader: "Requirements: 1. Add feature",
    requirements: ["Add feature"],
    weight: 1.0,
  };

  const substantialDiff = Array.from({ length: 25 }, (_, i) => `+ const line_${i} = ${i};`).join("\n");

  const cleanReport: CheatingAuditReport = {
    isCheatingSuspected: false,
    riskLevel: "CLEAN",
    confidenceScore: 0.0,
    signals: {
      monolithicCommit: false,
      rapidVelocity: false,
      authorMismatch: false,
      aiWatermarksDetected: false,
      insufficientProgression: false,
    },
    details: ["Iterative commits across 45 minutes."],
    findingsSummary: "Clean iterative commits.",
    gitMetrics: { totalCommits: 3, totalLinesAdded: 40, totalLinesDeleted: 0, durationMinutes: 45, authorList: ["alice"] },
    proposedMarkCap: 1.0,
    proposedMarkPenalty: 0.0,
  };

  const cleanResult = await evaluateStudentWorkHonestly(instructions, substantialDiff, ["c1", "c2", "c3"], cleanReport);

  assert.ok(cleanResult.proposedMark >= 0.7 && cleanResult.proposedMark <= 1.0);
  assert.equal(cleanResult.cheatingStatus, "CLEAN");
  assert.ok(cleanResult.whatStudentDid.length > 0);
  assert.ok(cleanResult.howTheySolved.length > 0);

  const flaggedReport: CheatingAuditReport = {
    isCheatingSuspected: true,
    riskLevel: "FLAGGED",
    confidenceScore: 0.9,
    signals: {
      monolithicCommit: true,
      rapidVelocity: false,
      authorMismatch: false,
      aiWatermarksDetected: false,
      insufficientProgression: true,
    },
    details: ["Monolithic single commit with 250 lines."],
    findingsSummary: "Single monolithic commit; suspected copy-paste.",
    gitMetrics: { totalCommits: 1, totalLinesAdded: 250, totalLinesDeleted: 0, durationMinutes: 0, authorList: ["alice"] },
    proposedMarkCap: 0.35,
    proposedMarkPenalty: 0.5,
  };

  const flaggedResult = await evaluateStudentWorkHonestly(instructions, substantialDiff, ["c1"], flaggedReport);

  assert.ok(flaggedResult.proposedMark <= 0.35);
  assert.ok(flaggedResult.proposedMark >= 0.0);
  assert.equal(flaggedResult.cheatingStatus, "FLAGGED");
  assert.ok(flaggedResult.cheatingDetails.includes("monolithic"));
});

