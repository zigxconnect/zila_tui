test("Anti-Cheating - parseGitLogOutput flags monolithic code dump", () => {
  const gitLogOutput = `COMMIT|abc1234|Alice Student|alice@example.com|1710000000|Mon Mar 10 10:00:00 2026|Initial entire solution
 1 file changed, 250 insertions(+)`;

  const commits = parseGitLogOutput(gitLogOutput);
  assert.equal(commits.length, 1);

  const analysis = analyzeGitHistoryForCheating("/dummy/folder", {
    commitsOverride: commits,
    studentUsername: "alice",
  });

  assert.equal(analysis.signals.monolithicCommit, true);
  assert.equal(analysis.isCheatingSuspected, true);
  assert.ok(analysis.proposedMarkCap <= 0.4);
  assert.ok(analysis.details.some(e => e.includes("Monolithic code dump")));
});

